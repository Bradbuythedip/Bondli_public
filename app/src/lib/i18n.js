// The site in two languages. English is the copy as it was written; Simplified Chinese is a second
// dictionary over the same keys, so the page has one set of strings and two ways to say them.
//
// Key style. Keys are flat, dotted, lowercase: "<section>.<thing>", where the section is the
// component or panel the string lives in (hero, pulse, tag, agg, tape, beat, movers, calls, lore,
// watch, live, boot, launch, panel, run, pos, hold, sweep, keys, footer, toast, unit, exit, state).
// A value is either a string with {name} placeholders, filled from the vars object, or a function
// of that same vars object when the sentence has to be assembled (English plurals and "and"
// joins, Chinese measure words). Strings that are the same in both languages (venue names, chain
// codes, tickers, $BNDLI, pump.fun, Arc, Robinhood Chain) are not keyed at all; they stay in the
// component. A key missing from zh falls back to en, and a key missing from both comes back as the
// key itself, so a gap is visible on the page rather than a crash.
//
// Units come through the dictionary too (unit.s / unit.m / unit.h), because "12s" and "3m" read as
// units in English and as "12秒" and "3分" in Chinese. Tweets and the share card are not here: they
// are posted to an English feed and stay English on purpose.
