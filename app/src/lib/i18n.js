export const DICT = { en, zh };

// A key that is present but null prints nothing: "paused: null" is not a reason.
const fill = (s, vars) => vars ? s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? (vars[k] == null ? "" : String(vars[k])) : m)) : s;

/** One language's translator. t(key, vars) resolves the key in that language, then in English, then
 *  gives the key back. t.lang names the language; t.has says whether a key is known anywhere. */
export function makeT(lang) {
  const d = DICT[lang] || en;
  const t = (key, vars) => {
    const v = key in d ? d[key] : en[key];
    if (v == null) return key;
    return typeof v === "function" ? v(vars || {}) : fill(v, vars);
  };
  t.lang = lang;
  t.has = key => key in d || key in en;
  return t;
}
/** English, for the strings that are posted off the site (tweets, the card) whatever the page shows. */
export const tEn = makeT("en");

const LangCtx = createContext({ lang: "en", setLang: () => {} });

export function LangProvider({ children, initial }) {
  const [lang, setLangState] = useState(() => (LANGS.includes(initial) ? initial : detectLang()));
  const setLang = (l) => { if (!LANGS.includes(l)) return; setLangState(l); try { localStorage.setItem(STORE_KEY, l); } catch {} };
  // The document says what language it is in, so a screen reader and the browser's own translator agree with the page.
  useEffect(() => { try { document.documentElement.lang = lang === "zh" ? "zh-CN" : "en"; } catch {} }, [lang]);
  const value = useMemo(() => ({ lang, setLang }), [lang]);
  return React.createElement(LangCtx.Provider, { value }, children);
}

export function useLang() { const { lang, setLang } = useContext(LangCtx); return [lang, setLang]; }
export function useT() { const { lang } = useContext(LangCtx); return useMemo(() => makeT(lang), [lang]); }
