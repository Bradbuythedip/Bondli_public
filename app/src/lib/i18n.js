export const LANGS = ["en", "zh"];
const STORE_KEY = "bondli_lang";

/** The language to start in: what this device chose last time, else the browser's own if it is
 *  Chinese, else English. Never throws -- localStorage can be blocked. */
export function detectLang() {
  try { const v = localStorage.getItem(STORE_KEY); if (LANGS.includes(v)) return v; } catch {}
  try {
    const langs = [navigator.language, ...(navigator.languages || [])].filter(Boolean);
    if (langs.some(l => /^zh/i.test(l))) return "zh";
  } catch {}
  return "en";
}

